# include <iostream>

using namespace std;
int main(){

    // AND operator
    cout << (6 & 10) << '\n';

    //OR operator
    cout << (6 | 10) << '\n';
    
    //XOR operator
    cout << (6 ^ 10) << '\n';

    //Left shift << operator
    cout << (10 << 2) << '\n';

    //Right shift >> operator
    cout << (10 >> 1) << '\n';
    return 0;
}